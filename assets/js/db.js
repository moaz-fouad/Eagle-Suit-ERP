  function saveExpense(x){
    const db=data();
    if(x.id){                                   // edit in place
      const i=db.expenses.findIndex(e=>e.id===x.id);
      if(i>=0) db.expenses[i]=Object.assign(db.expenses[i],x);
    }else{
      x.id=(db.expenses.reduce((a,b)=>Math.max(a,b.id),0)+1);
      x.no=x.no||nextExpNo();
      x.time=x.time||nowTime();
      db.expenses.unshift(x);
      db.seq.exp=(db.seq.exp||1001)+1;
    }
    save(); return x;
  }
  function deleteExpense(id){
    const db=data(); db.expenses=db.expenses.filter(e=>e.id!==id); save();
  }

  /* ---- Save invoice: decrement stock + push history + customer link ---- */
  function saveInvoice(inv){
    const db=data();
    // 1. resolve / create customer
    /* Customer matching is NAME-first: a name that isn't in the table yet is
       always added as a new customer. The phone is only used to enrich an
       existing record (never to merge two different names).                */
    const norm = v => String(v||'').replace(/\s+/g,' ').trim();
    const key  = norm(inv.cname);
    let c = db.customers.find(x=>norm(x.name)===key);
    const isNew = !c;
    if(!c){
      c={id:(db.customers.reduce((a,b)=>Math.max(a,b.id),0)+1),
         name:key, phone:inv.phone||'', addr:inv.addr||'', notes:'', created:today()};
      db.customers.push(c);
    } else {
      if(inv.phone && !c.phone) c.phone=inv.phone;
      if(inv.addr  && !c.addr ) c.addr =inv.addr;
    }
    inv.cid=c.id;
    // 2. decrement inventory
    inv.items.forEach(it=>{ const p=db.products.find(x=>x.id===it.pid);
      if(p){ p.qty=Math.max(0,p.qty-it.qty); } });
    // 3. store
    inv.id=(db.sales.reduce((a,b)=>Math.max(a,b.id),0)+1);
    inv.no=inv.no||nextInvNo();
    inv.time=inv.time||nowTime();          // hour:minute of the sale
    inv.newCustomer=isNew;
    db.sales.unshift(inv);
    db.seq.inv++;
    save();
    return inv;
  }
  function deleteInvoice(id,restock){
    const db=data(); const i=db.sales.findIndex(x=>x.id===id); if(i<0) return;
    if(restock){ db.sales[i].items.forEach(it=>{const p=db.products.find(x=>x.id===it.pid); if(p)p.qty+=it.qty;}); }
    db.sales.splice(i,1); save();
  }
