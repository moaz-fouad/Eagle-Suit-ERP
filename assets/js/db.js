/* ------------------------------ formatting ------------------------------ */
function money(n){ n=Number(n)||0;
  return n.toLocaleString('en-US',{minimumFractionDigits:2,maximumFractionDigits:2}); }
function cur(){ return DB.data().settings.currency||'ج.م'; }
function money2(n){ return money(n)+' '+cur(); }
function today(){ const d=new Date();
  return d.getFullYear()+'-'+String(d.getMonth()+1).padStart(2,'0')+'-'+String(d.getDate()).padStart(2,'0'); }
function nowTime(){ const d=new Date();
  return String(d.getHours()).padStart(2,'0')+':'+String(d.getMinutes()).padStart(2,'0'); }
/* 24h -> 12h with Arabic/English meridiem, e.g. "07:35 م" / "07:35 PM" */
function ftime(hm){
  if(!hm) return '';
  const p=String(hm).split(':'); let h=+p[0]||0; const m=p[1]||'00';
  const am = h<12;
  h = h%12; if(h===0) h=12;
  return String(h).padStart(2,'0')+':'+m+' '+(LANG==='ar'?(am?'ص':'م'):(am?'AM':'PM'));
}
function fdatetime(d,tm){ return fdate(d)+(tm?'  '+ftime(tm):''); }
function fdate(s){ if(!s) return '-'; const p=s.split('-'); return p[2]+'/'+p[1]+'/'+p[0]; }
function monthKey(s){ return (s||'').slice(0,7); }
